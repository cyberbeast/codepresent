package presentation

import "fmt"

// Step represents a single highlighted code segment and its synchronized narration.
type Step struct {
	StepNumber      int    `json:"step_number" jsonschema:"1-indexed step number"`
	FilePath        string `json:"file_path" jsonschema:"Path to the file containing the code to highlight"`
	StartLine       int    `json:"start_line" jsonschema:"1-indexed starting line number"`
	EndLine         int    `json:"end_line" jsonschema:"1-indexed ending line number"`
	FocusTarget     string `json:"focus_target,omitempty" jsonschema:"Optional symbol or expression name being explained"`
	Title           string `json:"title" jsonschema:"Short title for this step"`
	Narration       string `json:"narration" jsonschema:"Explanation text synchronized with the highlight"`
	DurationSeconds int    `json:"duration_seconds,omitempty" jsonschema:"Suggested auto-advance duration in seconds"`
}

// Story represents a complete multi-step code presentation generated by an AI agent.
type Story struct {
	Title string `json:"story_title" jsonschema:"Overall title of the code walkthrough"`
	Steps []Step `json:"steps" jsonschema:"Ordered list of presentation steps"`
}

// Validate checks that the story and all its steps have valid ranges and required fields.
func (s *Story) Validate() error {
	if s.Title == "" {
		return fmt.Errorf("story_title must not be empty")
	}
	if len(s.Steps) == 0 {
		return fmt.Errorf("story must contain at least one step")
	}
	for i := range s.Steps {
		step := &s.Steps[i]
		if step.FilePath == "" {
			return fmt.Errorf("step %d: file_path must not be empty", i+1)
		}
		if step.StartLine < 1 {
			return fmt.Errorf("step %d: start_line must be >= 1, got %d", i+1, step.StartLine)
		}
		if step.EndLine < step.StartLine {
			return fmt.Errorf("step %d: end_line (%d) must be >= start_line (%d)", i+1, step.EndLine, step.StartLine)
		}
		if step.Narration == "" {
			return fmt.Errorf("step %d: narration must not be empty", i+1)
		}
		if step.StepNumber == 0 {
			step.StepNumber = i + 1
		}
		if step.DurationSeconds <= 0 {
			step.DurationSeconds = 6
		}
	}
	return nil
}
